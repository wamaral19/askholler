type QuestionSeed = readonly [
  id: string,
  title: string,
  group: string,
  category: string,
  objective: string,
  method: string,
  role: "Core" | "Optional" | "Close",
  segment: string,
  trigger: string,
  question: string,
  primaryTag: string,
  additionalTag: string,
  seconds: number,
  probe1: string,
  probe2: string,
];

const q = (
  ...[
    id,
    title,
    group,
    category,
    objective,
    method,
    role,
    segment,
    trigger,
    question,
    primaryTag,
    additionalTag,
    seconds,
    probe1,
    probe2,
  ]: QuestionSeed
) => ({
  id: id.toLowerCase(),
  title,
  prompt: question,
  probes: [probe1, probe2],
  researchGoal: objective,
  core: role === "Core",
  library: {
    questionId: id,
    group,
    category,
    researchObjective: objective,
    methodCode: method,
    role,
    eligibleSegment: segment,
    suggestedTrigger: trigger,
    targetTags: [primaryTag, additionalTag],
    estimatedSeconds: seconds,
  },
});

